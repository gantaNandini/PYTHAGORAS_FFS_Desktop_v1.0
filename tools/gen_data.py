#!/usr/bin/env python3
"""Generate src/atlas/data.generated.js and schema.generated.js from the ATLAS Python package + CSV databases.
Usage: python tools/gen_data.py <path to ATLAS_API579_PART9>   (the package with ENGINE/ and the KPTC + KPSCL geometries)
The JavaScript port therefore uses exactly the same tables, field names, units, defaults and drop-down lists as ATLAS."""
import csv, json, sys
from pathlib import Path
pkg = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(pkg / 'ENGINE'))
from atlas_part9 import schema as S
from atlas_part9.database import growth_model_ids

data = pkg / 'ENGINE' / 'data'
def rows(name):
    with (data / name).open(newline='', encoding='utf-8-sig') as f:
        return [dict(r) for r in csv.DictReader(f)]

xi = list(csv.reader((data / 'api579_table9_3_xi.csv').open(newline='')))
D = {
    'materials': rows('materials_db.csv'),
    'growth': rows('growth_models.csv'),
    'growthIds': growth_model_ids(),
    'table92': rows('api579_table9_2_reference_temperature.csv'),
    'table9F2': rows('api579_table9F2_austenitic_jc.csv'),
    'table9F3': rows('api579_table9F3_jr_curves.csv'),
    'lrmax': rows('api579_fig9_19_lrmax.csv'),
    'toughnessMethods': rows('toughness_methods.csv'),
    'annex9d': rows('annex9d_methods.csv'),
    'kpsclInfluence': {r['coefficient']: [float(r['C%d' % i]) for i in range(5)] for r in rows('api579_table9B2_kpscl_influence.csv')},
    'kptc': {r['parameter']: float(r['value']) for r in rows('api579_9B3_1_9C3_1_kptc_rptc_constants.csv')},
    'xi': {'X': [float(x.split('=')[1]) for x in xi[0][1:]], 'Lr': [float(r[0]) for r in xi[1:]],
           'grid': [[float(v) for v in r[1:]] for r in xi[1:]]},
}
mat_ids = [r['material_id'] for r in D['materials']]
LISTS = {k: list(v) for k, v in S.LISTS.items()}
LISTS['MATERIAL_IDS'] = mat_ids
LISTS['GROWTH_IDS'] = ['FROM_MATERIAL_DB'] + [g for g in D['growthIds'] if g != 'FROM_MATERIAL_DB']
LISTS['JR_IDS'] = [r['jr_id'] for r in D['table9F3']]
specs = []
for r in D['materials']:
    sp = r.get('specification')
    if sp and sp != 'REFERENCE' and sp not in specs: specs.append(sp)
LISTS['SPEC_TEXT'] = specs
for cls in ('CARBON_STEEL', 'LOW_ALLOY_STEEL', 'AUSTENITIC_SS', 'REFERENCE'):
    LISTS['MAT_' + cls] = [r['material_id'] for r in D['materials'] if r['material_class'] == cls]
LISTS['XI_CAP_SI'] = ['110', '220']; LISTS['XI_CAP_FPS'] = ['100', '200']

fields = []
for f in S.FIELDS:
    fields.append({'name': f.name, 'sheet': f.sheet, 'label': f.label, 'kind': f.kind, 'si': f.si, 'fps': f.fps,
                   'list': f.lst, 'note': f.note, 'geo': f.geo})
SC = {'fields': fields, 'lists': LISTS, 'suggest': sorted(S.SUGGEST), 'sensVars': S.SENS_VARS,
      'projectFields': S.PROJECT_FIELDS, 'nTests': S.N_TESTS, 'nHist': S.N_HIST,
      'defaultHistory': [list(h) for h in S.DEFAULT_HISTORY], 'nProf': S.N_PROF,
      'defaultProfile': [list(r) for r in S.DEFAULT_PROFILE], 'geometries': list(S.GEOMETRIES),
      'dist': {'KPSCL1': S.DIST1, 'KPSCL2': S.DIST2}, 'inputFormats': {'mb': S.INP_MB, 'poly': S.INP_POLY, 'prof': S.INP_PROF}}
out = Path('src/atlas')
(out / 'data.generated.js').write_text('// GENERATED by tools/gen_data.py from the ATLAS CSV databases - do not edit.\nconst DATA = ' + json.dumps(D, separators=(',', ':')) + ';\nexport default DATA;\n', encoding='utf-8')
(out / 'schema.generated.js').write_text('// GENERATED by tools/gen_data.py from ATLAS schema.py - do not edit.\nconst SCHEMA = ' + json.dumps(SC, separators=(',', ':')) + ';\nexport default SCHEMA;\n', encoding='utf-8')
print('materials', len(D['materials']), 'growth rows', len(D['growth']), 'models', len(D['growthIds']), 'fields', len(fields))
